"""
Malleable C2 Detection Engineering & RoE Rule Generator
Generates NIDS signatures (Suricata / Snort) and Memory/PE Signatures (YARA)
for blue team verification, purple teaming, and RoE compliance audits.
"""

from typing import List, Dict
from backend.models import Profile


class DetectionEngine:
    """Creates defensive detection signatures from active Malleable C2 profiles."""

    def __init__(self, profile: Profile):
        self.profile = profile

    def generate_suricata_rules(self, base_sid: int = 1000100) -> str:
        """Generates Suricata 6/7 HTTP rules targeting the profile's network footprint."""
        p = self.profile
        rules: List[str] = [
            f"# =====================================================================",
            f"# Suricata NIDS Signatures for Profile: {p.name}",
            f"# Generated by Ostad Red Team Forge RoE Engine",
            f"# =====================================================================\n"
        ]

        sid = base_sid

        # 1. HTTP-GET Heartbeat Rule
        for uri in p.http_get.uris:
            rule = (
                f'alert http $HOME_NET any -> $EXTERNAL_NET any ('
                f'msg:"OSTAD-REDTEAM Malleable C2 Beacon Check-in [{uri}]"; '
                f'flow:established,to_server; '
                f'http.method; content:"{p.http_get.verb}"; '
                f'http.uri; content:"{uri}"; '
            )
            # Add Host header check if present
            host_header = next((h.value for h in p.http_get.client.headers if h.name.lower() == "host"), "")
            if host_header:
                rule += f'http.host; content:"{host_header}"; '

            rule += f'classtype:trojan-activity; sid:{sid}; rev:1;)'
            rules.append(rule)
            sid += 1

        # 2. HTTP-POST Exfiltration Rule
        for uri in p.http_post.uris:
            rule = (
                f'alert http $HOME_NET any -> $EXTERNAL_NET any ('
                f'msg:"OSTAD-REDTEAM Malleable C2 Beacon Exfiltration [{uri}]"; '
                f'flow:established,to_server; '
                f'http.method; content:"{p.http_post.verb}"; '
                f'http.uri; content:"{uri}"; '
            )
            host_header = next((h.value for h in p.http_post.client.headers if h.name.lower() == "host"), "")
            if host_header:
                rule += f'http.host; content:"{host_header}"; '

            rule += f'classtype:trojan-activity; sid:{sid}; rev:1;)'
            rules.append(rule)
            sid += 1

        return "\n".join(rules)

    def generate_snort_rules(self, base_sid: int = 2000100) -> str:
        """Generates Snort 2.9 / 3 compatible network rules."""
        p = self.profile
        rules = [
            f"# =====================================================================",
            f"# Snort NIDS Signatures for Profile: {p.name}",
            f"# Generated by Ostad Red Team Forge RoE Engine",
            f"# =====================================================================\n"
        ]
        sid = base_sid

        for uri in p.http_get.uris:
            rule = (
                f'alert tcp $HOME_NET any -> $EXTERNAL_NET $HTTP_PORTS ('
                f'msg:"OSTAD-REDTEAM Snort Malleable GET Pattern"; '
                f'flow:to_server,established; '
                f'content:"{p.http_get.verb} "; depth:5; '
                f'content:"{uri}"; http_uri; '
                f'sid:{sid}; rev:1;)'
            )
            rules.append(rule)
            sid += 1

        for uri in p.http_post.uris:
            rule = (
                f'alert tcp $HOME_NET any -> $EXTERNAL_NET $HTTP_PORTS ('
                f'msg:"OSTAD-REDTEAM Snort Malleable POST Pattern"; '
                f'flow:to_server,established; '
                f'content:"{p.http_post.verb} "; depth:6; '
                f'content:"{uri}"; http_uri; '
                f'sid:{sid}; rev:1;)'
            )
            rules.append(rule)
            sid += 1

        return "\n".join(rules)

    def generate_yara_rule(self) -> str:
        """Generates YARA memory & artifact detection rule."""
        p = self.profile
        rule_name = f"Ostad_MalleableC2_{p.name.replace(' ', '_').replace('-', '_')}"
        clean_rule_name = "".join(c for c in rule_name if c.isalnum() or c == '_')

        strings_block = []
        # Named Pipe string
        pipe_str = p.pipename.replace('##', '')
        strings_block.append(f'        $pipe = "\\\\\\\\.\\\\pipe\\\\{pipe_str}" ascii wide')

        # Custom Magic PE/MZ strings
        if p.stage.magic_mz_x86:
            strings_block.append(f'        $magic_mz = "{p.stage.magic_mz_x86}" ascii')
        if p.stage.magic_pe:
            strings_block.append(f'        $magic_pe = "{p.stage.magic_pe}" ascii')

        # Sample name
        if p.sample_name:
            strings_block.append(f'        $sample = "{p.sample_name}" ascii wide')

        # User agent fragment
        ua_frag = p.useragent[:30].replace('\\', '\\\\').replace('"', '\\"')
        strings_block.append(f'        $ua = "{ua_frag}" ascii')

        yara_lines = [
            f"rule {clean_rule_name} {{",
            f"    meta:",
            f'        description = "Detects Ostad Malleable C2 Beacon Profile Indicators"',
            f'        author = "Ostad Red Team Forge"',
            f'        date = "2026-11-19"',
            f'        reference = "Adversary Simulation RoE Audit"',
            f'        score = "85"',
            f"    strings:",
            "\n".join(strings_block),
            f"    condition:",
            f"        $pipe or ($magic_mz and $magic_pe) or ($sample and $ua)",
            f"}}"
        ]
        return "\n".join(yara_lines)
