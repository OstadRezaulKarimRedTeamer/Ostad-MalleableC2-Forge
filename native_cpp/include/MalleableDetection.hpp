#pragma once

#include "MalleableModels.hpp"
#include <string>
#include <sstream>

namespace OstadC2 {

class DetectionEngine {
public:
    static std::string generate_suricata(const Profile& p, int base_sid = 1000100) {
        std::ostringstream ss;
        ss << "# =====================================================================\n";
        ss << "# Suricata NIDS Signatures for Profile: " << p.name << "\n";
        ss << "# Generated by Ostad Red Team Forge RoE Engine (C++ Edition)\n";
        ss << "# =====================================================================\n\n";

        int sid = base_sid;
        for (const auto& uri : p.http_get.uris) {
            ss << "alert http $HOME_NET any -> $EXTERNAL_NET any ("
               << "msg:\"OSTAD-REDTEAM Malleable C2 Check-in [" << uri << "]\"; "
               << "flow:established,to_server; "
               << "http.method; content:\"" << p.http_get.verb << "\"; "
               << "http.uri; content:\"" << uri << "\"; "
               << "classtype:trojan-activity; sid:" << sid++ << "; rev:1;)\n";
        }
        for (const auto& uri : p.http_post.uris) {
            ss << "alert http $HOME_NET any -> $EXTERNAL_NET any ("
               << "msg:\"OSTAD-REDTEAM Malleable C2 Exfiltration [" << uri << "]\"; "
               << "flow:established,to_server; "
               << "http.method; content:\"" << p.http_post.verb << "\"; "
               << "http.uri; content:\"" << uri << "\"; "
               << "classtype:trojan-activity; sid:" << sid++ << "; rev:1;)\n";
        }
        return ss.str();
    }

    static std::string generate_snort(const Profile& p, int base_sid = 2000100) {
        std::ostringstream ss;
        ss << "# =====================================================================\n";
        ss << "# Snort NIDS Signatures for Profile: " << p.name << "\n";
        ss << "# Generated by Ostad Red Team Forge RoE Engine (C++ Edition)\n";
        ss << "# =====================================================================\n\n";

        int sid = base_sid;
        for (const auto& uri : p.http_get.uris) {
            ss << "alert tcp $HOME_NET any -> $EXTERNAL_NET $HTTP_PORTS ("
               << "msg:\"OSTAD-REDTEAM Snort Malleable Check-in\"; "
               << "flow:to_server,established; "
               << "content:\"" << p.http_get.verb << " \"; depth:5; "
               << "content:\"" << uri << "\"; http_uri; "
               << "sid:" << sid++ << "; rev:1;)\n";
        }
        for (const auto& uri : p.http_post.uris) {
            ss << "alert tcp $HOME_NET any -> $EXTERNAL_NET $HTTP_PORTS ("
               << "msg:\"OSTAD-REDTEAM Snort Malleable Exfiltration\"; "
               << "flow:to_server,established; "
               << "content:\"" << p.http_post.verb << " \"; depth:6; "
               << "content:\"" << uri << "\"; http_uri; "
               << "sid:" << sid++ << "; rev:1;)\n";
        }
        return ss.str();
    }

    static std::string generate_yara(const Profile& p) {
        std::ostringstream ss;
        std::string clean_name = p.name;
        for (char& c : clean_name) {
            if (!std::isalnum(static_cast<unsigned char>(c))) c = '_';
        }

        ss << "rule Ostad_MalleableC2_" << clean_name << " {\n";
        ss << "    meta:\n";
        ss << "        description = \"Detects Ostad Malleable C2 Beacon Profile Indicators (C++ Edition)\"\n";
        ss << "        author = \"Ostad Red Team Forge\"\n";
        ss << "        date = \"2026-11-19\"\n";
        ss << "        reference = \"Red Team RoE Adversary Emulation\"\n";
        ss << "    strings:\n";
        ss << "        $magic_mz = \"" << p.stage.magic_mz_x86 << "\" ascii\n";
        ss << "        $magic_pe = \"" << p.stage.magic_pe << "\" ascii\n";
        ss << "        $sample = \"" << p.sample_name << "\" ascii wide\n";
        ss << "        $ua = \"" << p.useragent.substr(0, 30) << "\" ascii\n";
        ss << "    condition:\n";
        ss << "        ($magic_mz and $magic_pe) or ($sample and $ua)\n";
        ss << "}\n";
        return ss.str();
    }
};

} // namespace OstadC2
